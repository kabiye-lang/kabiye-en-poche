/**
 * Configure Phosphor icons to work properly with NativeWind className prop
 */
export function iconWithClassName(...phosphorIcons: PhosphorIcon[]) {
  phosphorIcons.forEach((icon) => {
    cssInterop(icon, {
      className: {
        target: 'style',
        nativeStyleToProp: {
          color: true,
        },
      },
    })
  })
}

